package dev.emcc.sdk.model;

import dev.emcc.sdk.Message;
import java.util.List;
import java.util.Objects;
import java.util.UUID;
import org.jspecify.annotations.Nullable;

/**
 * A request to create, update or delete an object or a layer (ADR-0005). The object store answers
 * with exactly one {@link ChangeEvent} or {@link ChangeRejection} (model rule 12).
 *
 * <pre>{@code
 * ChangeRequest.update(newId(), objectId, current.version(), newContent, Actor.plugin("draw-symbols"))
 * }</pre>
 *
 * <p><b>Compatibility:</b> the 1.1.0 constructor without {@code fields} stays. Do not deconstruct
 * this record with a record pattern: it may gain components in later 1.x versions.
 *
 * @param requestId correlates the request with its answer
 * @param entityType object or layer
 * @param operation create, update or delete
 * @param entityId generated by the requester on create
 * @param baseVersion the version the change is based on; recorded, not enforced in 1.0.0
 * @param data the new content for create and update; {@code null} for delete
 * @param externalRef only for the create of an object: its identity in an external system (model rule 16); otherwise {@code null}
 * @param source the requesting plugin (the user is set by the server)
 * @param fields SDK 1.2.0: declared fields to set, only on the create and update of an object,
 *     at most {@link #MAX_FIELDS}; empty when there are none (ADR-0038)
 */
public record ChangeRequest(
    UUID requestId,
    EntityType entityType,
    Operation operation,
    UUID entityId,
    @Nullable Long baseVersion,
    @Nullable EntityContent data,
    @Nullable ExternalRef externalRef,
    Actor source,
    List<FieldValue> fields)
    implements Message {

  /** The most declared fields one request sets (data model 1.2.0). */
  public static final int MAX_FIELDS = 64;

  /** The 1.1.0 constructor: no declared fields. */
  public ChangeRequest(
      UUID requestId, EntityType entityType, Operation operation, UUID entityId, @Nullable Long baseVersion,
      @Nullable EntityContent data, @Nullable ExternalRef externalRef, Actor source) {
    this(requestId, entityType, operation, entityId, baseVersion, data, externalRef, source, List.of());
  }

  public ChangeRequest {
    Objects.requireNonNull(requestId, "requestId");
    Objects.requireNonNull(entityType, "entityType");
    Objects.requireNonNull(operation, "operation");
    Objects.requireNonNull(entityId, "entityId");
    Objects.requireNonNull(source, "source");
    if (baseVersion != null && baseVersion < 1) {
      throw new IllegalArgumentException("baseVersion must be >= 1: " + baseVersion);
    }
    if (operation == Operation.DELETE) {
      if (data != null) {
        throw new IllegalArgumentException("a delete carries no data");
      }
    } else {
      if (data == null) {
        throw new IllegalArgumentException("a " + operation.json() + " needs data");
      }
      if (data.entityType() != entityType) {
        throw new IllegalArgumentException("data is a " + data.entityType().json() + ", but entityType is " + entityType.json());
      }
    }
    if (externalRef != null && (operation != Operation.CREATE || entityType != EntityType.OBJECT)) {
      throw new IllegalArgumentException("only the create of an object carries an externalRef");
    }
    fields = List.copyOf(fields);
    if (!fields.isEmpty() && (operation == Operation.DELETE || entityType != EntityType.OBJECT)) {
      throw new IllegalArgumentException("only the create and update of an object carry declared fields");
    }
    if (fields.size() > MAX_FIELDS) {
      throw new IllegalArgumentException("at most " + MAX_FIELDS + " declared fields: " + fields.size());
    }
  }

  public static ChangeRequest create(UUID requestId, UUID entityId, EntityContent data, Actor source) {
    return new ChangeRequest(requestId, data.entityType(), Operation.CREATE, entityId, null, data, null, source);
  }

  /** The create of an object with its identity in an external system (model rule 16). */
  public static ChangeRequest create(UUID requestId, UUID entityId, MapObjectContent data, ExternalRef externalRef, Actor source) {
    return new ChangeRequest(requestId, EntityType.OBJECT, Operation.CREATE, entityId, null, data, externalRef, source);
  }

  public static ChangeRequest update(UUID requestId, UUID entityId, long baseVersion, EntityContent data, Actor source) {
    return new ChangeRequest(requestId, data.entityType(), Operation.UPDATE, entityId, baseVersion, data, null, source);
  }

  public static ChangeRequest delete(UUID requestId, EntityType entityType, UUID entityId, @Nullable Long baseVersion, Actor source) {
    return new ChangeRequest(requestId, entityType, Operation.DELETE, entityId, baseVersion, null, null, source);
  }
}
