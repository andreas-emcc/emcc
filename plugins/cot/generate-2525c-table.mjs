// Makes the closed table that converts a MIL-STD-2525C symbol (a 15-character code, as ATAK and WinTAK send it) to APP-6D/E and back
// (brief function 29, T-129). Run it when mil-sym-ts changes:
//   node plugins/cot/generate-2525c-table.mjs            writes server/src/main/java/dev/emcc/plugins/cot/codec/Sidc2525cTable.java
//   node plugins/cot/generate-2525c-table.mjs --check    fails if the file differs from what it would write (no file is touched)
//
// Where it comes from: mil-sym-ts 2.10.9 (Apache-2.0, @armyc2.c5isr.renderer/mil-sym-ts-web, a dependency of the repository's root
// package.json), its table `c2d_default` (C2DLookup): one record per 2525C basic symbol id ("S*G*UCI---*****": affiliation, status and
// the characters from the 11th on starred) with the APP-6D symbol set, the six-digit entity, the two sector modifiers and the SIDC
// version. Nothing is added or changed, except that the 8 records of version 15 (MIL-STD-2525E Change 1, a draft) are left out
// (brief function 29) and only symbols ("S...") are kept. The table is committed; this script and mil-sym-ts are not needed to build
// the plugin.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const out = join(here, 'server/src/main/java/dev/emcc/plugins/cot/codec/Sidc2525cTable.java');
const root = dirname(require.resolve('@armyc2.c5isr.renderer/mil-sym-ts-web/package.json'));
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const { C2DLookup } = await import('@armyc2.c5isr.renderer/mil-sym-ts-web');
C2DLookup.getInstance();
const records = C2DLookup.c2d.c2d.symbols;

const rows = [];
const seen = new Set();
let skipped15 = 0;
let normalised = 0; // records whose 11th character is not a star: mil-sym-ts's own lookup (getBasicSymbolID2525C) never finds them as they are
const defective = []; // records whose own sector modifier is not two digits (a defect in the source)
for (const r of records) {
  if (!r.basic.startsWith('S')) continue;
  if (r.ver === '15') {
    skipped15++;
    continue;
  }
  if (r.ver !== '10' && r.ver !== '11') throw new Error(`version ${r.ver} in ${r.basic}`);
  if (!/^S[*][A-Z*]\*[A-Z0-9*-]{11}$/.test(r.basic) || !/^\d\d$/.test(r.ss) || !/^\d{6}$/.test(r.ec)) throw new Error(`odd record ${JSON.stringify(r)}`);
  const s1 = r.s1 === '' || r.s1 === undefined ? '00' : r.s1;
  const s2 = r.s2 === '' || r.s2 === undefined ? '00' : r.s2;
  if (!/^\d\d$/.test(s1) || !/^\d\d$/.test(s2)) {
    defective.push(`${r.basic} (sector ${s1} ${s2})`);
    continue;
  }
  const basic = r.basic.slice(0, 10) + '*****'; // as getBasicSymbolID2525C makes it: the 11th to 15th characters starred
  if (basic !== r.basic) normalised++;
  if (seen.has(basic)) throw new Error(`duplicate ${basic}`);
  seen.add(basic);
  rows.push(`${basic} ${r.ver} ${r.ss} ${r.ec} ${s1} ${s2}`);
}

const CHUNK = 300; // a Java string constant holds at most 65 535 bytes
const chunks = [];
for (let i = 0; i < rows.length; i += CHUNK) chunks.push(rows.slice(i, i + CHUNK));
const body = chunks.map((c) => `    """\n${c.map((l) => '      ' + l).join('\n')}\n      """`).join(',\n');

const java = `package dev.emcc.plugins.cot.codec;

import java.util.List;

/**
 * GENERATED by {@code plugins/cot/generate-2525c-table.mjs}: do not edit by hand. The table that converts a MIL-STD-2525C symbol
 * to APP-6D or APP-6E and back (brief function 29), in the order of its source.
 *
 * <p><b>Derived from mil-sym-ts ${version}</b> (Apache-2.0, https://github.com/missioncommand/mil-sym-ts), its table {@code c2d_default}
 * (class {@code C2DLookup}): one row per 2525C basic symbol id with the APP-6D symbol set, entity, sectors 1 and 2 and the SIDC version.
 * The ${skipped15} records of version 15 (a draft of MIL-STD-2525E Change 1) are left out, and so are ${defective.length} with a sector that is not two digits (${defective.join(', ')}: a defect in the source). ${normalised} records have a dash or an H in the 11th character, which mil-sym-ts's own lookup never finds; their basic id has the 11th to 15th characters starred, as the lookup makes it (no two become the same). ${rows.length} rows.
 *
 * <p>A row is {@code basic version symbolSet entity sector1 sector2}, e.g. {@code S*G*UCI---***** 11 10 121100 00 00}: the basic id
 * has the affiliation (2nd), status (4th) and the 11th to 15th characters starred.
 */
final class Sidc2525cTable {

  /** The number of rows. */
  static final int COUNT = ${rows.length};

  /** The rows, in chunks (a string constant is limited to 65 535 bytes). */
  static final List<String> CHUNKS = List.of(
${body});

  private Sidc2525cTable() {}
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    // missing
  }
  if (current !== java) {
    console.error('Sidc2525cTable.java differs from what the generator writes');
    process.exit(1);
  }
  console.log(`Sidc2525cTable.java is up to date (${rows.length} rows, mil-sym-ts ${version})`);
} else {
  writeFileSync(out, java);
  console.log(`wrote ${out}: ${rows.length} rows (skipped ${skipped15} of version 15), mil-sym-ts ${version}`);
}
